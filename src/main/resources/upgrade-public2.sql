-- Additive upgrade for existing installations of the employee application.
-- Run while connected to database tm. Existing employee, attendance, and leave
-- rows are preserved; this script adds tables/columns and backfills the legacy
-- inclusive day count for existing leave requests.

ALTER TABLE public2.attendance
    DROP CONSTRAINT IF EXISTS ck_attendance_status;

ALTER TABLE public2.attendance
    ALTER COLUMN status TYPE VARCHAR(30);

ALTER TABLE public2.attendance
    ADD CONSTRAINT ck_attendance_status
        CHECK (status IN ('Present', 'Late', 'On leave', 'Half day leave'));

ALTER TABLE public2.leave_requests
    ADD COLUMN IF NOT EXISTS working_days INTEGER;

UPDATE public2.leave_requests
SET working_days = (end_date - start_date) + 1
WHERE working_days IS NULL;

ALTER TABLE public2.leave_requests
    ALTER COLUMN working_days SET NOT NULL;

ALTER TABLE public2.leave_requests
    DROP CONSTRAINT IF EXISTS ck_leave_requests_working_days;

ALTER TABLE public2.leave_requests
    ADD CONSTRAINT ck_leave_requests_working_days CHECK (working_days > 0);

CREATE TABLE IF NOT EXISTS public2.public_holidays (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    holiday_date DATE NOT NULL,
    name VARCHAR(120) NOT NULL,
    description VARCHAR(500),
    source VARCHAR(10) NOT NULL DEFAULT 'CUSTOM',
    CONSTRAINT pk_public_holidays PRIMARY KEY (id),
    CONSTRAINT ck_public_holiday_source CHECK (source = 'CUSTOM'),
    CONSTRAINT uk_public_holiday_date_name UNIQUE (holiday_date, name)
);

-- Keep company holidays, remove imported Google entries, and allow multiple holidays on one date.
ALTER TABLE public2.public_holidays
    ADD COLUMN IF NOT EXISTS source VARCHAR(10) NOT NULL DEFAULT 'CUSTOM';
ALTER TABLE public2.public_holidays
    DROP CONSTRAINT IF EXISTS uk_public_holiday_date;
ALTER TABLE public2.public_holidays
    DROP CONSTRAINT IF EXISTS uk_public_holiday_date_name;
ALTER TABLE public2.public_holidays
    ADD CONSTRAINT uk_public_holiday_date_name UNIQUE (holiday_date, name);
ALTER TABLE public2.public_holidays
    DROP CONSTRAINT IF EXISTS ck_public_holiday_source;
DELETE FROM public2.public_holidays WHERE source = 'GOOGLE';
ALTER TABLE public2.public_holidays
    ADD CONSTRAINT ck_public_holiday_source CHECK (source = 'CUSTOM');

CREATE TABLE IF NOT EXISTS public2.employee_profiles (
    employee_id VARCHAR(32) NOT NULL,
    father_name VARCHAR(120) NOT NULL,
    mother_name VARCHAR(120) NOT NULL,
    permanent_address TEXT NOT NULL,
    date_of_birth DATE NOT NULL,
    profile_image BYTEA,
    tenth_marks NUMERIC(5, 2) NOT NULL,
    intermediate_type VARCHAR(12) NOT NULL,
    intermediate_marks NUMERIC(5, 2) NOT NULL,
    education_group VARCHAR(120) NOT NULL,
    graduation_qualification VARCHAR(120) NOT NULL,
    graduation_specialization VARCHAR(160),
    graduation_group VARCHAR(120),
    postgraduate_qualification VARCHAR(120),
    postgraduate_specialization VARCHAR(160),
    aadhaar_number VARCHAR(12),
    pan_number VARCHAR(10),
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_employee_profiles PRIMARY KEY (employee_id),
    CONSTRAINT fk_employee_profiles_employee FOREIGN KEY (employee_id)
        REFERENCES public2.employees (employee_id) ON DELETE CASCADE,
    CONSTRAINT ck_employee_profile_marks CHECK (
        tenth_marks BETWEEN 0 AND 100 AND intermediate_marks BETWEEN 0 AND 100
    ),
    CONSTRAINT ck_employee_profile_intermediate_type CHECK (intermediate_type IN ('12th', 'Diploma'))
);

CREATE TABLE IF NOT EXISTS public2.employee_skills (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    employee_id VARCHAR(32) NOT NULL,
    skill_name VARCHAR(100) NOT NULL,
    CONSTRAINT pk_employee_skills PRIMARY KEY (id),
    CONSTRAINT uk_employee_skill UNIQUE (employee_id, skill_name),
    CONSTRAINT fk_employee_skills_employee FOREIGN KEY (employee_id)
        REFERENCES public2.employees (employee_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS public2.employee_certifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    employee_id VARCHAR(32) NOT NULL,
    certification_name VARCHAR(180) NOT NULL,
    CONSTRAINT pk_employee_certifications PRIMARY KEY (id),
    CONSTRAINT fk_employee_certifications_employee FOREIGN KEY (employee_id)
        REFERENCES public2.employees (employee_id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_public_holidays_date ON public2.public_holidays (holiday_date);
CREATE INDEX IF NOT EXISTS idx_employee_skills_employee ON public2.employee_skills (employee_id);
CREATE INDEX IF NOT EXISTS idx_employee_certifications_employee ON public2.employee_certifications (employee_id);
